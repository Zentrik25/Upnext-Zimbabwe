// Generates src/styles/tokens.generated.css (Tailwind v4 @theme) from src/design/tokens.json.
// `--check` fails if the committed file is out of date (used by CI and a unit test).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(resolve(root, "src/design/tokens.json"), "utf8"));
const out = resolve(root, "src/styles/tokens.generated.css");
// The staff site (Django Admin, apps/api) reads the same tokens as plain custom properties (D-45, D-46 proposal).
const staffOut = resolve(root, "../api/core/static/core/staff-tokens.css");

const lines = [
  "/* GENERATED by scripts/generate-tokens.mjs from src/design/tokens.json — do not edit. */",
  "/* Colours use the production value; reference values are exposed as --color-ref-* for tests only. */",
  "@theme {",
  "  /* Remove Tailwind's default palette, radii and shadows: only design-system tokens exist (D-39). */",
  "  --color-*: initial;",
  "  --radius-*: initial;",
  "  --shadow-*: initial;",
  "  --inset-shadow-*: initial;",
  "  --drop-shadow-*: initial;",
  "  --blur-*: initial;",
  "  --breakpoint-*: initial;",
  "  --font-*: initial;",
  "  --text-*: initial;",
  "  --font-weight-*: initial;",
  "  --tracking-*: initial;",
  "  --leading-*: initial;",
  "",
  "  --color-white: #ffffff;",
  "  --color-transparent: transparent;",
];
for (const [name, v] of Object.entries(tokens.colors)) {
  lines.push(`  --color-${name}: ${v.prod ?? v.ref};`);
  if (v.prod) lines.push(`  --color-ref-${name}: ${v.ref}; /* reference value, ${v.dev} */`);
}
lines.push(
  "",
  `  --font-sans: ${tokens.fontFamily};`,
  `  --font-mono: ${tokens.fontMono};`,
  "  --radius-none: 0px;",
);
for (const [k, v] of Object.entries(tokens.shadows)) lines.push(`  --shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.fontSizes)) lines.push(`  --text-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.fontWeights)) lines.push(`  --font-weight-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.tracking)) lines.push(`  --tracking-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.leading)) lines.push(`  --leading-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.radii))
  if (!k.startsWith("$")) lines.push(`  --radius-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.containers)) lines.push(`  --container-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.heights)) lines.push(`  --spacing-${k}: ${v};`);
for (const [k, v] of Object.entries(tokens.breakpoints))
  if (!k.startsWith("$")) lines.push(`  --breakpoint-${k}: ${v};`);
lines.push("}", "");
// Dark theme (D-40): the same tokens redefined on :root for an explicit choice only (data-theme="dark"). The default
// is the light theme on every device: the device's colour-scheme setting is deliberately NOT followed (owner, 2026-10-29).
// Tailwind utilities read these variables at run time.
const darkVars = [
  ...Object.entries(tokens.colors).map(([name, v]) => `  --color-${name}: ${v.dark};`),
  ...Object.entries(tokens.darkShadows).map(([k, v]) => `  --shadow-${k}: ${v};`),
  "  color-scheme: dark;",
];
lines.push(':root[data-theme="dark"] {', ...darkVars, "}", "");
const css = lines.join("\n");

const staffLines = [
  "/* GENERATED by apps/web/scripts/generate-tokens.mjs from apps/web/src/design/tokens.json — do not edit. */",
  "/* Staff site (Django Admin) tokens: production value of every colour, light by default (D-45); the dark theme is an",
  '   explicit choice only (data-theme="dark"), as on the public site. */',
  ":root {",
  ...Object.entries(tokens.colors).map(([name, v]) => `  --u-${name}: ${v.prod ?? v.ref};`),
  ...Object.entries(tokens.shadows).map(([k, v]) => `  --u-shadow-${k}: ${v};`),
  ...Object.entries(tokens.radii)
    .filter(([k]) => !k.startsWith("$"))
    .map(([k, v]) => `  --u-radius-${k}: ${v};`),
  `  --u-font: ${tokens.fontFamily.replace("var(--font-inter), ", "")};`,
  `  --u-font-mono: ${tokens.fontMono.replace("var(--font-source-code), ", "")};`,
  "  color-scheme: light;",
  "}",
  "",
  ':root[data-theme="dark"] {',
  ...Object.entries(tokens.colors).map(([name, v]) => `  --u-${name}: ${v.dark};`),
  ...Object.entries(tokens.darkShadows).map(([k, v]) => `  --u-shadow-${k}: ${v};`),
  "  color-scheme: dark;",
  "}",
  "",
];
const staffCss = staffLines.join("\n");

const targets = [
  [out, css, "tokens.generated.css"],
  [staffOut, staffCss, "staff-tokens.css"],
];
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [file, content, label] of targets) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {
      /* missing */
    }
    if (current !== content) {
      console.error(`${label} is out of date. Run: npm run tokens:generate`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log("tokens.generated.css and staff-tokens.css are up to date");
} else {
  for (const [file, content] of targets) {
    writeFileSync(file, content);
    console.log(`wrote ${file}`);
  }
}
